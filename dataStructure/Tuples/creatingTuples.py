# Empty Tuple 
empty = ()

# Tuple with items
point = (3 , 5)
colors = ("red", "green", "blue")

# Single item tuple need comma!

single = (42,) # Note the comma
not_tuple = (42) # This is just 42 in parentheses

# Without Parentheses (implicit)

coordinates = 10 , 20

# A single-item tuple needs a comma: (42,) not (42). Without the comma, Python thinks it's just parantheses around number!

