# Basic Parameters
""" Add parameters inside the parentheses when defining a function: """

def introduce(name , age):
  print(f"My name is {name}")
  print(f"I am {age} years old")

# Call with values
introduce("Alice,", 25)
introduce("sahil", 20)
introduce("suresh", 28)

# ! - the values you pass when calling a function are called "arguments". The variable in the fun ction definition are "parameters". Many people use these terms unterchangeably 