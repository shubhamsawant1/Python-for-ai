# For loop 

# The for loop is the most common loop in Python. Let's start simple:

# Repeat a specific number of times 

# Print number 0 through 4

for i in range(5):
  print(i)

# Count from different starting points

# count from 1 to 5

for i in range(1, 6):
  print(i)

# Output: 1 2 3 4 5

# Count by 2s

for i in range(0, 10, 2):
  print(i)

# Output: 0 2 4 6 8
